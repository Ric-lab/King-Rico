"""Measure existing alpha silhouettes and generate shared reel CSS. No art edits.
Run manually after changing a symbol: python3 scripts/reel-symbols.py (Pillow).
"""
from pathlib import Path
import json
import re
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ATLAS = 'assets/symbols-v7.webp'
SOURCES = [
    (10, 'Ingresso', 'assets/machine/ticket-symbol-v3.webp', None),
    (2, 'Circo', ATLAS, 2), (0, 'Capa', ATLAS, 0),
    (6, 'Moeda', ATLAS, 6), (8, 'Diamante', ATLAS, 8),
    (7, 'Coroa', ATLAS, 7),
    (5, 'Escudo', 'assets/symbols/shield-defense-rainbow-gold-v1.webp', None),
    (11, 'Roleta', ATLAS, 11),
    (12, 'Tony', 'assets/tony/head.webp', None),
    (13, 'Tucker', 'assets/tucker/head.webp', None),
    (14, 'Ray', 'assets/ray/head-v1.webp', None),
    (15, 'Controle', 'assets/machine/controller-symbol-v1.webp', None),
]
W, H = .90, .82
data, rules = [], []
for symbol, name, source, tile in SOURCES:
    image = Image.open(ROOT / source).convert('RGBA')
    iw, ih = image.size
    tw, ox = (iw / 12, tile * iw / 12) if tile is not None else (iw, 0)
    # Crop only in memory to measure alpha; never modify/export image pixels.
    region = image.crop((int(ox), 0, int(ox + tw), ih))
    box = region.getchannel('A').point(lambda x: 255 if x > 100 else 0).getbbox()
    x0, y0, x1, y1 = box
    scale = min(W / (x1 - x0), H / (y1 - y0))
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    bw, bh = iw * scale, ih * scale
    px = (.5 - (ox + cx) * scale) / (1 - bw) if abs(1 - bw) > 1e-9 else .5
    py = (.5 - cy * scale) / (1 - bh) if abs(1 - bh) > 1e-9 else .5
    left, top = .5 - cx * scale, .5 - cy * scale
    clip = [max(0, top), max(0, 1-left-tw*scale), max(0, 1-top-ih*scale), max(0, left)]
    record = dict(id=symbol, name=name, source=source, tile=tile, size=[iw, ih],
                  bounds=box, visible=[(x1-x0)*scale, (y1-y0)*scale])
    data.append(record)
    pct = lambda x: f'{x*100:.6f}%'
    rules.append(f'.park-reels [data-reel-symbol="{symbol}"]' + '{' +
                 f'--reel-art:url(\'/{source}\');--reel-size:{pct(bw)} {pct(bh)};' +
                 f'--reel-position:{pct(px)} {pct(py)};' +
                 '--reel-clip:' + ' '.join(map(pct, clip)) + ';}')

selector = ','.join(f'[data-reel-symbol="{x[0]}"]' for x in SOURCES)
common = ('.park-circus-stage .park-reels :is(' + selector + '){' +
          'background-image:var(--reel-art)!important;' +
          'background-size:var(--reel-size)!important;' +
          'background-position:var(--reel-position)!important;' +
          'background-repeat:no-repeat!important;clip-path:inset(var(--reel-clip));' +
          'backface-visibility:hidden;transform-origin:50% 86%;transform:translateZ(0);will-change:transform}')
header = ('/* Generated by scripts/reel-symbols.py. Existing art, alpha-centered.\n'
          '   Shared by all nine cells and moving tapes. Safe envelope:90% x82%.\n'
          '   Atlas clips prevent adjacent symbols bleeding into smaller tiles. */\n')
held = (
    '.park-circus-stage .park-reels>.park-reel-cell{transition:none}\n'
    '.park-circus-stage .park-reels .park-reel-cell[data-held="true"]{perspective:520px;perspective-origin:50% 50%}\n'
    '.park-circus-stage .park-reels .park-reel-cell[data-held="true"]>[data-reel-symbol]{transform-origin:50% 50%!important;transform:translateZ(0)}\n'
    '.park-reels>.park-part-reel-top[data-held="true"]>[data-reel-symbol]{rotate:x 15deg;scale:1 .96}\n'
    '.park-reels>.park-part-reel-bottom[data-held="true"]>[data-reel-symbol]{rotate:x -15deg;scale:1 .96}\n'
)
(ROOT/'ui/park/reel-symbols.css').write_text(header+common+'\n'+'\n'.join(rules)+'\n'+held)
(ROOT/'ui/park/reel-symbols.json').write_text(json.dumps(dict(envelope=[W,H],symbols=data),ensure_ascii=False,indent=2)+'\n')
sources = list(dict.fromkeys(s['source'] for s in data))
preloads = '<!-- reel-art-preload:start -->\n' + '\n'.join(
    f'<link rel="preload" as="image" href="./{s}" data-reel-preload>' for s in sources
) + '\n<!-- reel-art-preload:end -->'
page = ROOT/'Fortune Circus.dc.html'
html = page.read_text()
if '<!-- reel-art-preload:start -->' in html:
    html = re.sub(r'<!-- reel-art-preload:start -->.*?<!-- reel-art-preload:end -->', preloads, html, flags=re.S)
else:
    marker = '<link rel="stylesheet" href="./ui/park/reel-symbols.css">'
    assert marker in html
    html = html.replace(marker, marker+'\n'+preloads, 1)
page.write_text(html)
print('Measured12 symbols; wrote shared CSS and audit metadata. No image modified.')
